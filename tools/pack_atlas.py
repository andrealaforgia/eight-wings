#!/usr/bin/env python3
"""Pack assets/generated/**.png into assets/atlas.png + assets/atlas.txt and emit src/platform/sprite_table.h.

atlas.txt lines:  <name>[.<frame>] x y w h      (anchor = centre; frame suffix only for animations)
Deterministic shelf packing, 1px edge-extruded padding. Run `python3 tools/pack_atlas.py` (or `make assets`).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "assetgen"))
from spec import read_spec, files_for, ROOT  # noqa: E402
from pixlib import Canvas  # noqa: E402
import validate_assets as V  # noqa: E402

GEN = os.path.join(ROOT, "assets", "generated")
ATLAS_PNG = os.path.join(ROOT, "assets", "atlas.png")
ATLAS_TXT = os.path.join(ROOT, "assets", "atlas.txt")
HEADER = os.path.join(ROOT, "src", "platform", "sprite_table.h")
ATLAS_W = 1024
PAD = 1


def frame_entries():
    """[(fullname, w, h, rgba_rows)] in spec order."""
    out = []
    for e in read_spec():
        for i, f in enumerate(files_for(e, GEN)):
            w, h, rows = V.read_png(f)
            name = e["name"] if e["frames"] == 1 else "%s.%d" % (e["name"], i)
            out.append((name, w, h, rows))
    # utility texel block for solid rectangles (UI bars, overlays); not part of the art contract
    out.append(("_white", 4, 4, [bytearray([255, 255, 255, 255] * 4) for _ in range(4)]))
    return out


def pack(entries):
    order = sorted(range(len(entries)), key=lambda i: (-entries[i][2], -entries[i][1], entries[i][0]))
    x = y = shelf_h = 0
    placed = {}
    for i in order:
        name, w, h, _ = entries[i]
        if x + w + 2 * PAD > ATLAS_W:
            x, y, shelf_h = 0, y + shelf_h, 0
        placed[name] = (x + PAD, y + PAD)
        x += w + 2 * PAD
        shelf_h = max(shelf_h, h + 2 * PAD)
    height = 1
    while height < y + shelf_h:
        height *= 2
    return placed, height


def write_header():
    with open(HEADER, "w") as f:
        f.write("/* GENERATED by tools/pack_atlas.py from assets/spec/sprites.spec — do not edit. */\n#ifndef PLATFORM_SPRITE_TABLE_H_\n#define PLATFORM_SPRITE_TABLE_H_\n\n")
        f.write("#define SPRITE_LIST(X) \\\n")
        for e in read_spec():
            f.write("  X(%s, %d, %d, %d) \\\n" % (e["name"], e["w"], e["h"], e["frames"]))
        f.write("  /* end */\n\n#endif\n")


def main():
    if "--header-only" in sys.argv:
        write_header()
        print("header written")
        return
    entries = frame_entries()
    placed, height = pack(entries)
    atlas = Canvas(ATLAS_W, height)
    lines = []
    for name, w, h, rows in entries:
        ox, oy = placed[name]
        for yy in range(-PAD, h + PAD):
            for xx in range(-PAD, w + PAD):
                sx, sy = min(max(xx, 0), w - 1), min(max(yy, 0), h - 1)
                px = tuple(rows[sy][sx * 4:sx * 4 + 4])
                if xx != sx or yy != sy:   # padding: extrude edge colour but keep it transparent if the edge is
                    pass
                atlas.set(ox + xx, oy + yy, px)
        lines.append("%s %d %d %d %d" % (name, ox, oy, w, h))
    atlas.save_png(ATLAS_PNG)
    open(ATLAS_TXT, "w").write("# generated by tools/pack_atlas.py — name x y w h\n" + "\n".join(lines) + "\n")
    write_header()
    print("atlas %dx%d, %d frames -> assets/atlas.png, assets/atlas.txt, src/platform/sprite_table.h" % (ATLAS_W, height, len(entries)))


def verify():
    """Used by validate_assets: atlas matches sources, in bounds, no overlaps."""
    errors = []
    if not os.path.exists(ATLAS_TXT) or not os.path.exists(ATLAS_PNG):
        return ["atlas missing: run `make assets`"]
    aw, ah, arows = V.read_png(ATLAS_PNG)
    boxes = []
    seen = set()
    for line in open(ATLAS_TXT):
        if line.startswith("#") or not line.strip():
            continue
        name, x, y, w, h = line.split()
        x, y, w, h = int(x), int(y), int(w), int(h)
        seen.add(name)
        if x < 0 or y < 0 or x + w > aw or y + h > ah:
            errors.append("atlas: %s out of bounds" % name)
        for (n2, bx, by, bw, bh) in boxes:
            if x < bx + bw and bx < x + w and y < by + bh and by < y + h:
                errors.append("atlas: %s overlaps %s" % (name, n2))
        boxes.append((name, x, y, w, h))
    for e in read_spec():
        for i, f in enumerate(files_for(e, GEN)):
            name = e["name"] if e["frames"] == 1 else "%s.%d" % (e["name"], i)
            if name not in seen:
                errors.append("atlas: %s missing from metadata" % name)
                continue
            _, x, y, w, h = [l for l in open(ATLAS_TXT) if l.startswith(name + " ")][0].split()
            x, y, w, h = int(x), int(y), int(w), int(h)
            sw, sh, srows = V.read_png(f)
            for yy in range(h):
                if bytes(arows[y + yy][x * 4:(x + w) * 4]) != bytes(srows[yy][:w * 4]):
                    errors.append("atlas: %s pixels differ from source" % name)
                    break
    return errors


if __name__ == "__main__":
    main()
