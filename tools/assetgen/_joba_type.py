def mask(char,cell,tall):
    char=char.upper()
    if char not in PATHS: return None
    c=Canvas(6*cell,7*tall)
    radius=.69
    # Analytic capsule unions produce real native curves even on italic logo letters.
    paths=list(PATHS[char])
    if char=='0': paths=paths+[[(1.8,5.1),(4.2,1.9)]]
    for path in paths:
        for (x0,y0),(x1,y1) in zip(path,path[1:]):
            r=.31 if char=='0' and path is paths[-1] else radius
            dx,dy=x1-x0,y1-y0; length=dx*dx+dy*dy
            xmin=max(0,math.floor((min(x0,x1)-r)*cell))
            xmax=min(c.w-1,math.ceil((max(x0,x1)+r)*cell))
            ymin=max(0,math.floor((min(y0,y1)-r)*tall))
            ymax=min(c.h-1,math.ceil((max(y0,y1)+r)*tall))
            for y in range(ymin,ymax+1):
                for x in range(xmin,xmax+1):
                    xx,yy=(x+.5)/cell,(y+.5)/tall
                    t=max(0,min(1,((xx-x0)*dx+(yy-y0)*dy)/length))
                    if (xx-x0-t*dx)**2+(yy-y0-t*dy)**2<=r*r:
                        c.set(x,y,'white')
    return c
