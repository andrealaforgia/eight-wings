def glyph(char):
    return GLYPHS[char.upper() if char.islower() else char].split('/')


def lettering(canvas, char, x, y, colour='white', cell=4, tall=None):
    """Native contour chamfers preserve wide counters and continuous uprights."""
    tall=cell if tall is None else tall
    from _joba_type import mask as outline_glyph
    vector=outline_glyph(char,cell,tall)
    if vector is not None:
        vector.replace('white',colour)
        canvas.blit(vector,x,y)
        return
    rows=glyph(char)
    mask=Canvas(len(rows[0])*cell,7*tall)
    for yy,row in enumerate(rows):
        for xx,pixel in enumerate(row):
            if pixel=='1': mask.rect(xx*cell,yy*tall,cell,tall,'white')
    source=mask.copy()
    chamfer=max(1,min(cell,tall)//3)
    for yy in range(mask.h):
        for xx in range(mask.w):
            if not source.get(xx,yy)[3]: continue
            cut=False
            # Chamfer only exposed convex corners, leaving counters generously open.
            for dx,dy in ((-1,-1),(1,-1),(-1,1),(1,1)):
                if (not source.get(xx+dx*chamfer,yy)[3] and
                    not source.get(xx,yy+dy*chamfer)[3]):
                    cut=True
            if cut and char.isalnum(): continue
            canvas.set(x+xx,y+yy,colour)


def component_icon(number):
    from _joba_ultra import canvas, panel, enamel, line
    c=canvas(8,8)
    panel(c,[(.25,1),(.9,.25),(7.1,.25),(7.75,1),(7.75,7),
             (7.1,7.75),(.9,7.75),(.25,7)])
    enamel(c,[(.7,1.1),(1.2,.7),(6.8,.7),(7.3,1.1),(7.3,6.9),
              (6.8,7.3),(1.2,7.3),(.7,6.9)],number)
    # Four native texels per logical cell: the numeral is still almost 7px tall.
    lettering(c,str(number),6,3,cell=3,tall=3)
    line(c,.6,1.5,.6,6.4,ACCENTS[number-1][3])
    return c


def logo():
    from _joba_ultra import canvas, panel, poly, line, BLUE
    c=canvas(192,48)
    wing=[(1,8),(54,15),(95.8,.7),(95.8,46),(55,36),(1,42),(22,25)]
    panel(c,wing,BLUE)
    panel(c,[(192-x,y) for x,y in wing],BLUE)
    for side in (-1,1):
        for i in range(5):
            x=96+side*(28+i*9.5)
            line(c,x,15,x+side*11,21,'c1')
            line(c,x,37,x+side*11,31,'b1')
            line(c,x,15.5,x+side*11,21.5,'b4')
    poly(c,[(96,1),(101,12),(115,23),(101,29),(96,47),(91,29),(77,23),(91,12)],'b1')
    line(c,96,1,96,46,'c3')
    mask=Canvas(c.w,c.h)
    x=60
    for char in 'EIGHT WINGS':
        if char==' ':
            x+=38
            continue
        letter=Canvas(48,112)
        lettering(letter,char,0,0,cell=8,tall=16)
        for yy in range(letter.h):
            for xx in range(letter.w):
                if letter.get(xx,yy)[3]:
                    mask.set(x+xx+(112-yy)//6,32+yy,'white')
        x+=61
    shadow=mask.copy(); shadow.replace('white','ink'); shadow.outline('ink',True)
    for offset in range(13,0,-1): c.blit(shadow,offset,offset)
    edge=mask.copy(); edge.outline('ink',True); c.blit(edge,0,0)
    cool=('white','c4','c3','b4','b3','b2','b1')
    warm=('y2','y1','o3','o2','r3','r2')
    for y in range(c.h):
        for x in range(c.w):
            if not mask.get(x,y)[3]: continue
            col=cool[min(6,max(0,(y-32)//9))] if y<91 else warm[min(5,(y-91)//9)]
            if not mask.get(x-1,y)[3] or not mask.get(x,y-1)[3]:
                col='white' if y<91 else 'y2'
            elif not mask.get(x+1,y)[3] or not mask.get(x,y+1)[3]:
                col='c1' if y<91 else 'r1'
            elif not mask.get(x-2,y)[3] or not mask.get(x,y-2)[3]:
                col='c4' if y<91 else 'y1'
            c.set(x,y,col)
    for x,y in ((15,8.5),(178,9)):
        line(c,x-3,y,x+3,y,'c3'); line(c,x,y-3,x,y+3,'c3')
        line(c,x-1.5,y,x+1.5,y,'white'); line(c,x,y-1.5,x,y+1.5,'white')
    return c


def generate():
    for code in range(32,127):
        c=Canvas(32,32)
        lettering(c,chr(code),4,2)
        emit('font',c,code-32,group='ui')
    for i in range(8): emit('ui_comp',component_icon(i+1),i,group='ui')
    from _joba_ultra import canvas, panel, line, BLUE
    c=canvas(8,8)
    panel(c,[(4,.4),(3,3),(0,6),(1,7),(3,6),(4,7),(5,6),
             (7,7),(8,6),(5,3)],BLUE)
    line(c,3.6,2,3.6,5.5,'white'); line(c,4.1,3,4.1,5.7,'c3')
    line(c,3.2,6.8,4.7,6.8,'o3'); c.outline('ink')
    emit('ui_life',c,group='ui')
    emit('logo_title',logo(),group='ui')


if __name__=='__main__': generate()
